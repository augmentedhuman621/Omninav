#!/usr/bin/env python3
"""B-03 verification fixture (runs on the local WSL only): use a pty to simulate
"the lidar is streaming data" and regress check_lidar.sh.

Why a pty: the slave side of `pty.openpty()` is just a tty device to the script --
  * `stty -F <slave>` can set termios (same behaviour as a real serial port);
  * bytes written to the master end show up in the slave's read stream.
So it proves that `probe_read()`'s `timeout cat | od` pipeline really does return
bytes when data is present, instead of being swallowed into 0 bytes by pipefail +
`|| out=""` (B-03 / B2 regression). It also proves that the fixed argument parsing
treats `--device DEV` and `--device=DEV` identically (B1 regression).

Boundary: does not touch the Pi or real hardware, does not modify the system; uses
a pty at /tmp level only and changes no other repository file.
Output: `pi_setup/check_lidar_fix_pty.log` (UTF-8, all raw output); exit code
0 = all assertions pass, 1 = some failed.

Usage (WSL Ubuntu): `python3 pi_setup/check_lidar_fix_pty_test.py`
"""
import os
import pty
import re
import subprocess
import sys
import threading
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(ROOT, "pi_setup", "check_lidar.sh")
LOG = os.path.join(ROOT, "pi_setup", "check_lidar_fix_pty.log")

PATTERN = bytes([0x54, 0x2C]) + b"\x00" * 46  # fake data with the LD19 header 54 2c
ENV = dict(os.environ, OMNINAV_SKIP_ARCH_CHECK="1")

checks = []  # (ok: bool, name, detail)
raw_chunks = []


def check(ok, name, detail=""):
    checks.append((bool(ok), name, detail))
    print(("[PASS] " if ok else "[FAIL] ") + name + (("  | " + detail) if detail else ""))


def run_script(args, timeout=120):
    p = subprocess.run(
        ["bash", SCRIPT] + args,
        capture_output=True, text=True, timeout=timeout, env=ENV,
    )
    out = p.stdout + p.stderr
    raw_chunks.append("$ bash %s %s\nEXIT=%d\n%s\n" % (SCRIPT, " ".join(args), p.returncode, out))
    return p.returncode, out


def main():
    if not os.path.exists(SCRIPT):
        print("Script not found: %s" % SCRIPT)
        return 1

    # ---------- 0. syntax / integrity (raw evidence goes to a separate log) ----------
    import hashlib
    with open(SCRIPT, "rb") as f:
        raw = f.read()
    sha = hashlib.sha256(raw).hexdigest()
    lines = raw.count(b"\n")
    syntax = subprocess.run(["bash", "-n", SCRIPT], capture_output=True, text=True)
    check(syntax.returncode == 0, "bash -n syntax check passed", "EXIT=%d %s" % (syntax.returncode, syntax.stderr.strip()))
    syntax_log = [
        "# check_lidar.sh syntax and integrity check (B-03, generated by check_lidar_fix_pty_test.py)\n",
        "time=%s\n" % time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "command: bash -n %s\n" % SCRIPT,
        "SYNTAX_EXIT=%d\n" % syntax.returncode,
        "sha256=%s\n" % sha,
        "lines=%d\n" % lines,
    ]
    with open(os.path.join(ROOT, "pi_setup", "check_lidar_fix_syntax.log"), "w", encoding="utf-8") as f:
        f.write("".join(syntax_log))

    results = {}

    # ---------- B1: argument parsing (space form vs equals form) ----------
    rc_help, out_help = run_script(["--help"])
    check(rc_help == 2, "B1 --help exit code = 2", "actual %d" % rc_help)
    check("--device DEV" in out_help and "--device=DEV" in out_help,
          "B1 usage documents both --device DEV and --device=DEV", "")

    rc_bad, out_bad = run_script(["--device"])
    check(rc_bad == 2, "B1 `--device` (missing argument) exit code = 2", "actual %d" % rc_bad)
    check("requires an argument" in out_bad, "B1 missing `--device` argument gives a clear message", "")

    rc_empty, out_empty = run_script(["--device="])
    check(rc_empty == 2, "B1 `--device=` (empty value) exit code = 2", "actual %d" % rc_empty)
    check("must not be empty" in out_empty, "B1 empty `--device=` gives a clear message", "")

    rc_dash, out_dash = run_script(["--device", "--probe"])
    check(rc_dash == 2, "B1 `--device --probe` (value looks like an option) exit code = 2", "actual %d" % rc_dash)

    rc_unknown, out_unknown = run_script(["--bogus"])
    check(rc_unknown == 2, "B1 unknown option exit code = 2", "actual %d" % rc_unknown)

    # Both forms target /dev/null (opens, but stty must fail => fast, no hardware)
    rc_eq, out_eq = run_script(["--probe", "--device=/dev/null"])
    rc_sp, out_sp = run_script(["--probe", "--device", "/dev/null"], timeout=180)
    check(rc_eq == rc_sp, "B1 `--device=X` and `--device X` exit codes agree",
          "equals form %d / space form %d" % (rc_eq, rc_sp))
    check("Probe device = /dev/null" in out_eq and "Probe device = /dev/null" in out_sp,
          "B1 both forms really use /dev/null as the probe device", "")
    check(rc_eq != 2, "B1 equals form no longer treated as an argument error (exit != 2)", "actual %d" % rc_eq)
    check(rc_sp != 2, "B1 space form no longer treated as an argument error (exit != 2, was 2 before the fix)", "actual %d" % rc_sp)

    # ---------- B2: report stty failure separately from 0 bytes (/dev/null opens but is not a tty) ----------
    check("stty failed on /dev/null" in out_eq, "B2 stty failure has its own message (not 0 bytes)", "")
    check("Verdict: D2" in out_eq or "probe not executed: stty cannot configure the device" in out_eq,
          "B2 verdict section reports D2/not executed separately (distinct from 0 bytes)", "")
    check("probe not executed this round" in out_eq, "B2 explicitly says the probe was not executed", "")
    check("All candidate baud rates produced 0 bytes" not in out_eq,
          "B2 stty failure no longer misreports \"all 0 bytes\"", "")

    # ---------- B2: pty-simulated data (core regression: always 0 bytes before the fix) ----------
    master, slave = pty.openpty()
    slave_name = os.ttyname(slave)
    stop = threading.Event()

    def writer():
        while not stop.is_set():
            try:
                os.write(master, PATTERN)
            except OSError:
                break
            time.sleep(0.02)

    t = threading.Thread(target=writer, daemon=True)
    t.start()
    try:
        rc_pty, out_pty = run_script(["--probe", "--device", slave_name], timeout=180)
    finally:
        stop.set()
        t.join(timeout=2)
        os.close(master)
        os.close(slave)

    m = re.search(r"passively received (\d+) bytes", out_pty)
    bytes_seen = int(m.group(1)) if m else 0
    check(bytes_seen > 0, "B2 --probe reads bytes when the pty has data (was always 0 before the fix)",
          "read %d bytes, pty=%s" % (bytes_seen, slave_name))
    check("contains 54 2c (LD19 header signature)" in out_pty, "B2 recognises the 54 2c header signature", "")
    check("Verdict: D2 probe preconditions not met" not in out_pty, "B2 pty data path does not misjudge D2", "")
    check(rc_pty != 2, "B2 pty probe run was not interrupted by argument/environment errors", "EXIT=%d" % rc_pty)

    # ---------- read-only boundary: the script must not really install / modify the system ----------
    with open(SCRIPT, "r", encoding="utf-8", errors="replace") as f:
        src = f.read()
    # Only look at "lines that would be executed": a command must start the line; apt
    # install inside hint text does not count
    exec_lines = [ln.strip() for ln in src.splitlines()
                  if not ln.lstrip().startswith("#") and re.match(r"^\s*(sudo\s+)?(apt|apt-get|pip3?|dnf|yum|snap)\s+(install|remove)\b", ln)]
    check(not exec_lines, "read-only boundary: no install/remove command execution lines", "hits %s" % exec_lines if exec_lines else "")
    danger = re.findall(r"(?m)^\s*(?:sudo\s+)?(?:tee|cp|mv|rm|chmod|chown|usermod|udevadm\s+control)\b[^\n]*/(?:etc|usr|opt|lib)\b", src)
    check(not danger, "read-only boundary: no execution lines writing /etc /usr /opt", "hits %s" % danger if danger else "")
    check(src.count('>"$PROBE_DEV"') == 1 and '>"$dev"' not in src,
          "read-only boundary: the only device write is the 2-byte --request-rplidar request", "")

    # ---------- summary ----------
    ok_n = sum(1 for c in checks if c[0])
    print("\n==== Assertion summary: %d/%d passed ====" % (ok_n, len(checks)))
    raw_chunks.append("\n==== Assertion summary: %d/%d passed ====\n" % (ok_n, len(checks)))
    for ok, name, detail in checks:
        raw_chunks.append(("[PASS] " if ok else "[FAIL] ") + name + (("  | " + detail) if detail else "") + "\n")
    with open(LOG, "w", encoding="utf-8") as f:
        f.write("".join(raw_chunks))
    print("Raw output written to: %s" % LOG)
    return 0 if ok_n == len(checks) else 1


if __name__ == "__main__":
    sys.exit(main())
